import {readdirSync,lstatSync,mkdirSync,readFileSync,writeFileSync,cpSync,rmSync,existsSync,appendFileSync} from 'node:fs';
import {resolve,join} from 'node:path';
import {fileURLToPath} from 'node:url';
function directory(path){if(lstatSync(path).isSymbolicLink()||!lstatSync(path).isDirectory())throw new Error('Expected real directory');}
function validateTree(root){
 directory(root);
 for(const entry of readdirSync(root)){
  if(entry==='.git'||entry==='.github')throw new Error('Git metadata is forbidden in site artifacts');
  const path=join(root,entry),stat=lstatSync(path);
  if(stat.isSymbolicLink()||(!stat.isFile()&&!stat.isDirectory()))throw new Error('Only regular site files are allowed');
  if(stat.isDirectory())validateTree(path);
 }
}
export function updateSite({root,source,mode,sha,number,snapshot,now=Date.now()}){
 root=resolve(root);directory(root);
 for(const reserved of ['pr','previews'])if(existsSync(join(root,reserved)))directory(join(root,reserved));
 if(!['production','review','preview','cleanup'].includes(mode))throw new Error('Invalid publication mode');
 let path='',changed=false;
 if(mode!=='cleanup'){
  if(!/^[0-9a-f]{40}$/.test(sha??''))throw new Error('Invalid commit');
  source=resolve(source);validateTree(source);
  if(!existsSync(join(source,'index.html')))throw new Error('Missing index');
  const report=JSON.parse(readFileSync(join(source,mode==='production'?'build-info.json':'changes.json'),'utf8'));
  if(report.head!==sha)throw new Error('Wrong source commit');
  if(mode==='production'){
   if(['pr','previews'].some(name=>existsSync(join(source,name))))throw new Error('Reserved site directory');
   for(const name of readdirSync(root))if(!['pr','previews','.git'].includes(name))rmSync(join(root,name),{recursive:true,force:true});
   cpSync(source,root,{recursive:true});
  }else{
   if(!/^[1-9][0-9]*-[1-9][0-9]*$/.test(snapshot??''))throw new Error('Invalid snapshot');
   if(mode==='review'&&!/^[1-9][0-9]*$/.test(number??''))throw new Error('Invalid PR');
   path=mode==='review'?`pr/${number}/${sha}/${snapshot}/`:`previews/${snapshot}/`;
   const destination=join(root,path);
   if(existsSync(destination))throw new Error('Snapshot already exists; rerun build with a new attempt');
   // State branch is generated by this script; artifacts cannot populate its reserved trees.
   const segments=path.split('/').filter(Boolean);let parent=root;
   for(const segment of segments){parent=join(parent,segment);if(existsSync(parent))directory(parent);}
   mkdirSync(destination,{recursive:true});cpSync(source,destination,{recursive:true});
   writeFileSync(join(destination,'published.json'),JSON.stringify({publishedAt:now,head:sha}));
   changed=Object.values(report.environments).some(env=>Object.values(env.changes).some(rows=>rows.length>0));
  }
 }
 function prune(dir){
  if(!existsSync(dir))return;directory(dir);
  for(const entry of readdirSync(dir)){
   const child=join(dir,entry);if(!lstatSync(child).isDirectory())continue;directory(child);
   const stamp=join(child,'published.json');
   if(existsSync(stamp)){
    if(lstatSync(stamp).isSymbolicLink())throw new Error('Invalid timestamp file');
    if(JSON.parse(readFileSync(stamp,'utf8')).publishedAt<now-30*86400000)rmSync(child,{recursive:true});
   }else prune(child);
  }
 }
 prune(join(root,'pr'));prune(join(root,'previews'));writeFileSync(join(root,'.nojekyll'),'');
 return {path,changed};
}
if(process.argv[1]&&resolve(process.argv[1])===fileURLToPath(import.meta.url)){
 const result=updateSite({root:'.pages-state',source:process.env.PAGES_SOURCE,mode:process.env.PAGES_MODE,sha:process.env.PAGES_SHA,number:process.env.PAGES_PR,snapshot:process.env.PAGES_SNAPSHOT});
 if(process.env.GITHUB_OUTPUT)appendFileSync(process.env.GITHUB_OUTPUT,`path=${result.path}\nchanged=${result.changed}\n`);
 console.log(`Published ${process.env.PAGES_MODE}: ${result.path||'/'}`);
}
